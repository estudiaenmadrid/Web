import type { CSSProperties } from "react";
import { photoSrc, photoSrcSet, type Photo as PhotoData } from "@/lib/photos";

type PhotoSource =
  | { photo: PhotoData }
  /** A remote placeholder (lib/photos.ts PLACEHOLDER_SLOT_IMAGES) — colour originals, so greyed out in CSS. */
  | { placeholder: { src: string; alt: string; focal: [number, number] } };

type PhotoProps = PhotoSource & {
  /** The rendered width per breakpoint, so the browser picks the right file from the srcset. */
  sizes: string;
  priority?: boolean;
  className?: string;
  style?: CSSProperties;
};

/**
 * Fills its (positioned, aspect-ratio'd) parent with a cover-cropped photo
 * anchored on the photo's focal point. A plain <img> on purpose: this is a
 * static export with no image optimizer, and the responsive WebP set is
 * already pre-generated by scripts/fotos.mjs.
 */
export default function Photo(props: PhotoProps) {
  const { sizes, priority, className, style } = props;
  const common = {
    loading: priority ? ("eager" as const) : ("lazy" as const),
    fetchPriority: priority ? ("high" as const) : undefined,
    decoding: "async" as const,
    className: className ?? "absolute inset-0 w-full h-full",
  };

  if ("placeholder" in props) {
    const { src, alt, focal } = props.placeholder;
    return (
      // eslint-disable-next-line @next/next/no-img-element -- see component doc
      <img
        {...common}
        src={src}
        alt={alt}
        sizes={sizes}
        style={{
          objectFit: "cover",
          objectPosition: `${focal[0]}% ${focal[1]}%`,
          filter: "grayscale(1) contrast(1.06)",
          ...style,
        }}
      />
    );
  }

  const { photo } = props;
  return (
    // eslint-disable-next-line @next/next/no-img-element -- see component doc
    <img
      {...common}
      src={photoSrc(photo, photo.widths.find((w) => w >= 1024) ?? photo.width)}
      srcSet={photoSrcSet(photo)}
      sizes={sizes}
      width={photo.width}
      height={photo.height}
      alt={photo.alt}
      style={{
        objectFit: "cover",
        objectPosition: `${photo.focal[0]}% ${photo.focal[1]}%`,
        backgroundImage: photo.blur ? `url(${photo.blur})` : undefined,
        backgroundSize: "cover",
        backgroundPosition: `${photo.focal[0]}% ${photo.focal[1]}%`,
        ...style,
      }}
    />
  );
}
